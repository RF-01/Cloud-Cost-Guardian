"""Cost estimates from the internal price table (design §11.1, CONTRACT §3.1).

USD per month as a Decimal rounded to 2 places, or None when the resource can't be priced (one `price_unknown`
JSON log line with the reason; never raises). Never calls a pricing or billing API at run time: the table is
scanner/src/scanner/prices_data.py, generated by scanner/tools/build_price_table.py.

- ec2: what stopping saves = on-demand Linux hourly price x 730, plus public IPv4 x 730 for each auto-assigned
  public IPv4 (NetworkInterfaces[].Association with IpOwnerId "amazon": released on stop). EBS volumes and Elastic
  IPs stay billed after a stop (Elastic IPs have their own findings), so they are not included. Other operating
  systems are not priced.
- ebs: size x GB-month price, plus gp3 IOPS above 3,000 and throughput above 125 MiB/s, plus io1 / io2
  provisioned IOPS (io2 tiered).
- eip: public IPv4 x 730.
- estimate_snapshot: size x snapshot GB-month price, an upper bound (a snapshot stores only used blocks).
"""

import json
import threading
from decimal import ROUND_HALF_UP, Decimal

HOURS_PER_MONTH = Decimal(730)
GP3_FREE_IOPS = 3000
GP3_FREE_THROUGHPUT = 125  # MiB/s
LINUX = "Linux/UNIX"
CENT = Decimal("0.01")

_table = None
_table_lock = threading.Lock()  # first lazy load can happen in several region threads at once; read-only after


def _prices(table):
    global _table
    if table is not None:
        return table
    if _table is None:
        with _table_lock:
            if _table is None:
                from scanner import prices_data
                _table = prices_data.PRICES
    return _table


class _Unknown(Exception):
    pass


def _log_unknown(resource_type, region, resource_id, reason):
    print(json.dumps({"resourceId": resource_id, "resourceType": resource_type, "region": region,
                      "action": "price_unknown", "result": "skipped", "reason": reason}))


def _region(table, region):
    prices = table.get(region)
    if prices is None:
        raise _Unknown(f"region {region!r} not in the price table")
    return prices


def _get(mapping, key, what):
    value = mapping.get(key)
    if value is None:
        raise _Unknown(f"no {what} price for {key!r}")
    return value


def _number(resource, key, default=None):
    value = resource.get(key)
    if value is None:
        if default is None:
            raise _Unknown(f"resource has no {key}")
        return Decimal(default)
    return Decimal(str(value))


def _ec2(prices, inst):
    platform = inst.get("PlatformDetails")
    if platform != LINUX:
        raise _Unknown(f"platform {platform!r} is not priced (only {LINUX})")
    hourly = Decimal(_get(prices["ec2"], inst.get("InstanceType"), "instance type"))
    auto_ips = {eni["Association"].get("PublicIp") for eni in inst.get("NetworkInterfaces", []) or []
                if (eni.get("Association") or {}).get("IpOwnerId") == "amazon"}
    ipv4 = Decimal(prices["ipv4"]["in_use"]) * len(auto_ips)
    return (hourly + ipv4) * HOURS_PER_MONTH


def _io2_iops(tiers, iops):
    cost, below = Decimal(0), Decimal(0)
    for up_to, price in tiers:
        top = iops if up_to is None else min(iops, Decimal(up_to))
        if top > below:
            cost += (top - below) * Decimal(price)
        if up_to is None or iops <= up_to:
            break
        below = Decimal(up_to)
    return cost


def _ebs(prices, vol):
    vtype = vol.get("VolumeType")
    cost = _number(vol, "Size") * Decimal(_get(prices["ebs"], vtype, "volume type"))
    iops = prices["iops"]
    if vtype == "gp3":
        extra_iops = max(_number(vol, "Iops", GP3_FREE_IOPS) - GP3_FREE_IOPS, 0)
        extra_mibps = max(_number(vol, "Throughput", GP3_FREE_THROUGHPUT) - GP3_FREE_THROUGHPUT, 0)
        cost += extra_iops * Decimal(_get(iops, "gp3", "IOPS"))
        cost += extra_mibps * Decimal(_get(prices, "gp3_throughput", "throughput"))
    elif vtype == "io1":
        cost += _number(vol, "Iops") * Decimal(_get(iops, "io1", "IOPS"))
    elif vtype == "io2":
        cost += _io2_iops(_get(iops, "io2", "IOPS"), _number(vol, "Iops"))
    return cost


def _eip(prices, addr):
    key = "in_use" if addr.get("AssociationId") else "idle"
    return Decimal(_get(prices["ipv4"], key, "IPv4")) * HOURS_PER_MONTH


_ESTIMATORS = {"ec2": (_ec2, "InstanceId"), "ebs": (_ebs, "VolumeId"), "eip": (_eip, "AllocationId")}


def _round(value):
    return value.quantize(CENT, rounding=ROUND_HALF_UP)


def estimate(resource_type, region, resource, table=None):
    """Estimated USD per month (Decimal, 2 places) for "ec2" | "ebs" | "eip", or None if it can't be priced.

    resource: the raw Describe* dict. table: injected in tests (default: prices_data.PRICES).
    """
    resource = resource or {}
    estimator, id_key = _ESTIMATORS.get(resource_type, (None, None))
    resource_id = resource.get(id_key) or resource.get("PublicIp") if id_key else None
    try:
        if estimator is None:
            raise _Unknown(f"resource type {resource_type!r} is not priced")
        return _round(estimator(_region(_prices(table), region), resource))
    except _Unknown as err:
        reason = str(err)
    except Exception as err:  # a bad price or resource shape must never stop the scan
        reason = f"error: {type(err).__name__}: {err}"
    _log_unknown(resource_type, region, resource_id, reason)
    return None


def estimate_snapshot(region, size_gb, table=None, resource_id=None):
    """Upper bound of a full snapshot of `size_gb` GB per month (Decimal, 2 places), or None."""
    try:
        prices = _region(_prices(table), region)
        if size_gb is None:
            raise _Unknown("no size")
        return _round(Decimal(str(size_gb)) * Decimal(_get(prices, "snapshot", "snapshot")))
    except _Unknown as err:
        reason = str(err)
    except Exception as err:
        reason = f"error: {type(err).__name__}: {err}"
    _log_unknown("snapshot", region, resource_id, reason)
    return None
